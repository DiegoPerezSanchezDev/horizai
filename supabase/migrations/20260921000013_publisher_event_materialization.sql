-- HorizAI / Fase 10D
-- Atomically resolves or materializes an event before publishing its article.
-- PostgreSQL owns event/article UUID generation. No RLS changes.

create or replace function public.publish_article_atomic(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_event_id uuid;
  v_article_id uuid;
  v_existing_article_id uuid;
  v_region_id uuid;
  v_region_latitude numeric;
  v_region_longitude numeric;
  v_region_code text;
  v_source jsonb;
  v_category jsonb;
  v_entity jsonb;
  v_category_id uuid;
  v_entity_id uuid;
  v_raw_item_id uuid;
  v_event_action text;
  v_article_action text;
  v_existing_title text;
  v_entity_created boolean;
  v_relation_exists boolean;
  v_row_count integer;
  v_event_source_created integer := 0;
  v_relations_created integer := 0;
  v_entities_created integer := 0;
  v_entities_reused integer := 0;
  v_sources_count integer;
  v_primary_source_count integer;
begin
  if jsonb_typeof(p_payload) <> 'object' then
    raise exception using errcode = 'P0001', message = 'publication_transaction_failed';
  end if;

  if p_payload->'critic'->>'decision' <> 'pass' then
    raise exception using errcode = 'P0001', message = 'publication_not_approved';
  end if;

  if nullif(p_payload->>'eventKey', '') is null then
    raise exception using errcode = 'P0001', message = 'publication_lineage_mismatch';
  end if;

  -- Resolve all registry-only references before the first write.
  v_region_code := nullif(p_payload->'region'->>'code', '');
  if v_region_code is not null then
    select id, latitude, longitude
      into v_region_id, v_region_latitude, v_region_longitude
      from public.regions
     where code = v_region_code and is_active = true;
    if v_region_id is null then
      raise exception using errcode = 'P0001', message = 'publication_invalid_region';
    end if;
    if (p_payload->'region'->>'latitude')::numeric is distinct from v_region_latitude
       or (p_payload->'region'->>'longitude')::numeric is distinct from v_region_longitude then
      raise exception using errcode = 'P0001', message = 'publication_invalid_geo';
    end if;
  elsif p_payload->'region'->>'latitude' is not null
     or p_payload->'region'->>'longitude' is not null then
    raise exception using errcode = 'P0001', message = 'publication_invalid_geo';
  end if;

  select count(*) into v_sources_count from jsonb_array_elements(p_payload->'sources');
  if v_sources_count < 1 then
    raise exception using errcode = 'P0001', message = 'publication_missing_source';
  end if;

  select count(*) into v_primary_source_count
    from jsonb_array_elements(p_payload->'sources') as requested
   where (requested->>'isPrimary')::boolean;
  if v_primary_source_count > 1 then
    raise exception using errcode = 'P0001', message = 'publication_source_traceability_missing';
  end if;

  for v_source in select value from jsonb_array_elements(p_payload->'sources') loop
    if not exists (select 1 from public.sources where id = (v_source->>'sourceId')::uuid) then
      raise exception using errcode = 'P0001', message = 'publication_missing_source';
    end if;
  end loop;

  for v_category in select value from jsonb_array_elements(p_payload->'categories') loop
    select id into v_category_id
      from public.categories
     where slug = v_category->>'categorySlug' and is_active = true;
    if v_category_id is null then
      raise exception using errcode = 'P0001', message = 'publication_invalid_category';
    end if;
  end loop;

  -- The event UUID is generated by PostgreSQL. A concurrent caller either
  -- inserts the event or waits and reuses the unique event_key row.
  insert into public.events (
    event_key, canonical_title, event_status, confidence_score,
    primary_region_id, primary_country_code, occurred_at,
    review_status, review_notes, last_seen_at
  ) values (
    p_payload->>'eventKey',
    p_payload->'event'->>'canonicalTitle',
    'active',
    (p_payload->'verification'->>'confidenceScore')::numeric / 100,
    v_region_id,
    nullif(p_payload->'event'->>'probableCountryCode', ''),
    nullif(p_payload->'event'->>'probableOccurredAt', '')::timestamptz,
    'approved',
    p_payload->'critic'->>'notes',
    now()
  )
  on conflict (event_key) do nothing
  returning id into v_event_id;

  if v_event_id is not null then
    v_event_action := 'created';
  else
    select id, canonical_title into v_event_id, v_existing_title
      from public.events
     where event_key = p_payload->>'eventKey'
     for update;
    if v_event_id is null then
      raise exception using errcode = 'P0001', message = 'publication_transaction_failed';
    end if;
    if v_existing_title <> p_payload->'event'->>'canonicalTitle' then
      raise exception using errcode = 'P0001', message = 'publication_idempotency_conflict';
    end if;
    v_event_action := 'reused';
  end if;

  -- Existing events must already carry the exact source traceability. New
  -- events require an explicit rawItemId per source; no raw item is guessed.
  if v_event_action = 'reused' then
    for v_source in select value from jsonb_array_elements(p_payload->'sources') loop
      if not exists (
        select 1 from public.event_sources
         where event_id = v_event_id
           and source_id = (v_source->>'sourceId')::uuid
      ) then
        raise exception using errcode = 'P0001', message = 'publication_source_traceability_missing';
      end if;
    end loop;
  else
    for v_source in select value from jsonb_array_elements(p_payload->'sources') loop
      v_raw_item_id := nullif(v_source->>'rawItemId', '')::uuid;
      if v_raw_item_id is null then
        raise exception using errcode = 'P0001', message = 'publication_missing_raw_item';
      end if;
      if not exists (
        select 1 from public.raw_items
         where id = v_raw_item_id
           and source_id = (v_source->>'sourceId')::uuid
      ) then
        raise exception using errcode = 'P0001', message = 'publication_missing_raw_item';
      end if;
      insert into public.event_sources (event_id, raw_item_id, source_id, is_primary)
      values (v_event_id, v_raw_item_id, (v_source->>'sourceId')::uuid, coalesce((v_source->>'isPrimary')::boolean, false))
      on conflict (event_id, raw_item_id) do nothing;
      get diagnostics v_row_count = row_count;
      v_event_source_created := v_event_source_created + v_row_count;
    end loop;
  end if;

  select id into v_existing_article_id
    from public.articles
   where event_id = v_event_id
   for update;

  insert into public.articles (
    event_id, slug, headline_es, summary_es, why_it_matters_es, body_es,
    importance_score, confidence_score, publication_status, critic_status,
    critic_notes, generated_at, reviewed_at, published_at, metadata
  ) values (
    v_event_id,
    p_payload->'article'->>'slug',
    p_payload->'article'->>'headlineEs',
    p_payload->'article'->>'summaryEs',
    p_payload->'article'->>'whyItMattersEs',
    p_payload->'article'->>'bodyEs',
    (p_payload->'scores'->>'importanceScore')::numeric,
    (p_payload->'verification'->>'confidenceScore')::numeric / 100,
    'published',
    'approved',
    p_payload->'critic'->>'notes',
    now(), now(), now(),
    jsonb_build_object(
      'publisherVersion', 'publisher-v1',
      'dekEs', p_payload->'article'->>'dekEs',
      'keyPoints', p_payload->'article'->'keyPoints'
    )
  )
  on conflict (event_id) do update set
    slug = excluded.slug,
    headline_es = excluded.headline_es,
    summary_es = excluded.summary_es,
    why_it_matters_es = excluded.why_it_matters_es,
    body_es = excluded.body_es,
    importance_score = excluded.importance_score,
    confidence_score = excluded.confidence_score,
    publication_status = excluded.publication_status,
    critic_status = excluded.critic_status,
    critic_notes = excluded.critic_notes,
    reviewed_at = excluded.reviewed_at,
    published_at = excluded.published_at,
    metadata = excluded.metadata,
    updated_at = now()
  returning id into v_article_id;

  if v_existing_article_id is null then v_article_action := 'created';
  else v_article_action := 'updated';
  end if;

  for v_category in select value from jsonb_array_elements(p_payload->'categories') loop
    select id into v_category_id
      from public.categories
     where slug = v_category->>'categorySlug' and is_active = true;
    select exists (
      select 1 from public.article_categories
       where article_id = v_article_id and category_id = v_category_id
    ) into v_relation_exists;
    insert into public.article_categories (article_id, category_id, is_primary, confidence_score)
    values (v_article_id, v_category_id, (v_category->>'isPrimary')::boolean, (v_category->>'confidenceScore')::numeric / 100)
    on conflict (article_id, category_id) do update set
      is_primary = excluded.is_primary,
      confidence_score = excluded.confidence_score,
      updated_at = now();
    if not v_relation_exists then
      v_relations_created := v_relations_created + 1;
    end if;
  end loop;

  for v_entity in select value from jsonb_array_elements(p_payload->'entities') loop
    v_entity_id := null;
    select id into v_entity_id
      from public.entities
     where entity_type = v_entity->>'entityType'
       and canonical_name = v_entity->>'canonicalName'
       and coalesce(country_code, '') = coalesce(nullif(v_entity->>'countryCode', ''), '');
    if v_entity_id is not null then
      v_entities_reused := v_entities_reused + 1;
    else
      insert into public.entities (entity_type, canonical_name, country_code)
      values (v_entity->>'entityType', v_entity->>'canonicalName', nullif(v_entity->>'countryCode', ''))
      on conflict (entity_type, canonical_name, (coalesce(country_code, ''))) do nothing
      returning id into v_entity_id;
      if v_entity_id is null then
        select id into v_entity_id
          from public.entities
         where entity_type = v_entity->>'entityType'
           and canonical_name = v_entity->>'canonicalName'
           and coalesce(country_code, '') = coalesce(nullif(v_entity->>'countryCode', ''), '')
         for update;
        v_entities_reused := v_entities_reused + 1;
      else
        v_entities_created := v_entities_created + 1;
      end if;
    end if;
    if not exists (select 1 from public.article_entities where article_id = v_article_id and entity_id = v_entity_id) then
      v_relations_created := v_relations_created + 1;
    end if;
    insert into public.article_entities (article_id, entity_id, role, confidence_score)
    values (v_article_id, v_entity_id, v_entity->>'role', (v_entity->>'confidenceScore')::numeric / 100)
    on conflict (article_id, entity_id) do update set
      role = excluded.role,
      confidence_score = excluded.confidence_score,
      updated_at = now();
  end loop;

  v_relations_created := v_relations_created + v_event_source_created;

  return jsonb_build_object(
    'eventId', v_event_id,
    'articleId', v_article_id,
    'eventAction', v_event_action,
    'articleAction', v_article_action,
    'articleOperation', 'upsert_by_event_id',
    'categoriesLinkedCount', jsonb_array_length(p_payload->'categories'),
    'entitiesLinkedCount', jsonb_array_length(p_payload->'entities'),
    'entitiesCreated', v_entities_created,
    'entitiesReused', v_entities_reused,
    'sourcesLinkedCount', v_sources_count,
    'relationsCreated', v_relations_created,
    'activityRowsCreated', 0
  );
exception
  when others then
    if sqlstate = 'P0001' then raise; end if;
    raise exception using errcode = 'P0001', message = 'publication_transaction_failed';
end;
$$;

revoke all on function public.publish_article_atomic(jsonb) from public, anon, authenticated;
grant execute on function public.publish_article_atomic(jsonb) to service_role;

comment on function public.publish_article_atomic(jsonb)
  is 'Atomically resolves or materializes an approved event and publishes its article for server-side HorizAI use.';
