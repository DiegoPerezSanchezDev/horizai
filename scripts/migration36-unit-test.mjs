import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parseCliJson, assertOnlyM36DryRun } from "./migration36-validation-runner.mjs";
import { migration36Filename, buildSupabaseMigrationArguments } from "./supabase-direct-migration-command.mjs";

const migration = readFileSync(`supabase/migrations/${migration36Filename}`, "utf8");
const preview = readFileSync("scripts/migration36-remote-preview-rollback.sql", "utf8");
const fixture = readFileSync("scripts/migration36-remote-rollback-fixture.sql", "utf8");
const functionDefinition = migration.slice(migration.indexOf("create or replace function"), migration.indexOf("$function$;") + "$function$;".length);
assert.ok(preview.includes(functionDefinition), "the PostgreSQL preview must execute the exact final migration function");
assert.ok(preview.includes(fixture), "the preview and post-migration fixture must execute identical cases");
assert.equal((migration.match(/select 1 from public\.pipeline_event_attempts a/g) ?? []).length, 2);
assert.equal((migration.match(/a\.completed_at is null or a\.final_state is null/g) ?? []).length, 2);
assert.equal((migration.match(/greatest\(r\.started_at, r\.finished_at, r\.updated_at, l\.created_at\)/g) ?? []).length, 2);
assert.match(migration, /auth\.role\(\) is distinct from 'service_role'/);
assert.match(migration, /set search_path = pg_catalog, public, pg_temp/);
assert.match(migration, /pg_advisory_xact_lock/);
assert.match(migration, /v_result := public\.reserve_groq_request_and_tokens\(/);
assert.doesNotMatch(migration, /2026-09|2026-10|\bgrant\b|alter table|\bdelete\b|\bupdate\b/i);
assert.match(preview, /M36_PREVIEW_FORCE_ROLLBACK/);
assert.match(preview, /m36_preview_function_not_restored/);
assert.match(fixture, /for v_case in 1\.\.14 loop/);
assert.match(fixture, /M36_CASE_FORCE_ROLLBACK/);
assert.match(fixture, /m36_fixture_residual_rows_not_zero/);
assert.match(fixture, /claim_pipeline_event_attempt_capacity_resume_m35/);
assert.match(fixture, /counts_toward_retry_limit=false/);
assert.doesNotMatch(fixture, /\bcommit\s*;/i);
assert.doesNotMatch(preview, /\bcommit\s*;/i);
assert.match(preview, /^do \$preview\$/);
assert.match(fixture, /^do \$fixture\$/);
assert.deepEqual(assertOnlyM36DryRun(`Would push: ${migration36Filename}`), [migration36Filename]);
assert.throws(() => assertOnlyM36DryRun("Already up to date"), /NOT_EXACTLY_ONE/);
assert.throws(() => assertOnlyM36DryRun(`${migration36Filename}\n20261014120000_verifier_first_stage_capacity_resume.sql`), /NOT_EXACTLY_ONE/);
assert.deepEqual(parseCliJson('Connecting...\n{"rows":[{"name":"brace } in string"}]}\nversion'), { rows: [{ name: "brace } in string" }] });
assert.throws(() => parseCliJson('Connecting...\n{"rows":'), /INCOMPLETE/);
for (const action of ["m36-acl", "m36-preview", "m36-fixture", "m36-residual"]) assert.equal(buildSupabaseMigrationArguments(action)[1], "query");
console.log("M36 generic lifecycle predicate, ACL/lock preservation, rollback-only fixtures, exact-pending gate, and CLI parsing: PASS (offline)");
